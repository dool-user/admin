"""note 記事のハッシュタグ（#）を決める（10/2 社長の指示）

アカウント（マガジン）ごとの基本のタグ＋タイトルの言葉で足すタグ。1記事 最大8個。
公開用の本文の最後に1行で入れ、公開キットでは公開設定のハッシュタグ欄にも貼れるようにする。
直したいときは BASE・RULES を編集する（読者が検索しそうな言葉にする。誇大な言葉は入れない。製品名は説明のためだけに使い、公式・提携と誤解させない）。
"""
import re

BASE = {
    'A01': ['AI活用', 'ClaudeCode', '業務効率化', '生成AI'],
    'A02': ['営業', 'フォーム営業', '営業のコツ', '中小企業'],
    'A03': ['MEO', 'Googleマップ', 'Googleビジネスプロフィール', '店舗集客'],
    'A11': ['引越し', '新生活', '一人暮らし', '関東'],
}
RULES = [
    (r'権限|消されない|安全', ['AIエージェント', 'セキュリティ']),
    (r'営業チーム|組織|SV|AP', ['AIエージェント', '営業組織']),
    (r'CLAUDE\.md|review\.md|仕事の渡し方', ['プロンプト', 'AIエージェント']),
    (r'mistakes|失敗', ['仕組み化']),
    (r'Instagram|DM', ['Instagram', 'DM営業']),
    (r'点検|チェック', ['チェックリスト']),
    (r'口コミ', ['口コミ']),
    (r'業者', ['業者選び']),
    (r'勝手に変わ|停止|制限', ['トラブル対応']),
    (r'部屋探し|物件|内見|秋冬', ['部屋探し', '賃貸']),
    (r'仲介手数料', ['仲介手数料', '賃貸']),
    (r'解約|退去', ['退去']),
    (r'プロパン|ガス', ['ガス']),
    (r'電気|水道|ライフライン|お湯', ['ライフライン']),
    (r'ネット|回線', ['ネット回線']),
    (r'ウォーターサーバー', ['ウォーターサーバー']),
    (r'見積もり|引越し業者|キャンセル', ['引越し業者']),
    (r'転勤', ['転勤']),
    (r'住所変更|転入|マイナ', ['住所変更', 'マイナンバーカード']),
    (r'3月|春|繁忙期', ['繁忙期']),
    (r'チェックリスト|やること', ['チェックリスト']),
]


def tags_for(title, acc, limit=8):
    out = list(BASE.get(acc, []))
    for pat, add in RULES:
        if re.search(pat, title):
            out += [t for t in add if t not in out]
    return out[:limit]


def tag_line(title, acc):
    return ' '.join('#' + t for t in tags_for(title, acc))
